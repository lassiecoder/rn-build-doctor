// Regenerates docs/supported-checks.md from the rule metadata in dist/. Run `npm run build` first.
import { writeFileSync } from "node:fs";
import { allRuleMeta } from "../dist/engine/registry.js";

const rules = allRuleMeta();
const section = (title, list) => [
  `## ${title}`,
  "",
  ...list.flatMap((r) => [
    `### \`${r.id}\``,
    "",
    `**${r.title}**`,
    "",
    `| Field | Value |`,
    `| --- | --- |`,
    `| Platforms | ${r.platforms.join(", ")} |`,
    `| Applicable versions | ${r.versionScope} |`,
    `| Trigger | ${r.trigger.replace(/\|/g, "\\|")} |`,
    `| Evidence | ${r.evidence.replace(/\|/g, "\\|")} |`,
    `| Sources | ${r.references.length ? r.references.map((u) => `<${u}>`).join("<br>") : "— (fallback rule)"} |`,
    `| Regression fixtures | ${r.fixtures.map((f) => `\`tests/fixtures/${f}\``).join("<br>")} |`,
    `| Last verified | ${r.lastVerified} |`,
    "",
  ]),
];

const out = [
  "# Supported checks",
  "",
  "<!-- Generated by `npm run catalog` from the rule metadata. Do not edit by hand. -->",
  "",
  "Every rule has a stable id, a documented trigger, the evidence it attaches, its sources, and regression fixtures in `tests/fixtures`. Confidence levels mean:",
  "",
  "- **high**: the evidence directly satisfies the rule's condition (for example, the exact error line is present).",
  "- **medium**: the evidence matches a known pattern, but an important detail is missing or can't be observed locally.",
  "- **low**: the symptom is suggestive but not enough to establish a cause.",
  "",
  "High confidence in a finding doesn't mean the suggested fix is safe for your project. Review each next step.",
  "",
  `${rules.length} rules: ${rules.filter((r) => r.scope === "project").length} project checks (\`scan\`) and ${rules.filter((r) => r.scope === "log").length} log rules (\`analyze\`).`,
  "",
  ...section(
    "Project checks (`scan`)",
    rules.filter((r) => r.scope === "project"),
  ),
  ...section(
    "Log analysis (`analyze`)",
    rules.filter((r) => r.scope === "log"),
  ),
].join("\n");

writeFileSync(new URL("../docs/supported-checks.md", import.meta.url), out);
console.log(`Wrote docs/supported-checks.md (${rules.length} rules)`);
